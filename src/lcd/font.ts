/** Text -> columns of 7-bit masks (bit 0 = top row), 1 blank column between glyphs. */
export function textColumns(text: string): number[] {
  const cols: number[] = [];
  for (const ch of text) {
    const rows = G[ch] ?? G['-']!;
    for (let c = 0; c < 5; c++) {
      let m = 0;
      for (let r = 0; r < 7; r++) if (rows[r]! & (1 << (4 - c))) m |= 1 << r;
      cols.push(m);
    }
    cols.push(0);
  }
  return cols;
}
