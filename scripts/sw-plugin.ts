// Emits sw.js at build time with every output file precached (no runtime dependency).
// Offline after first load: cache-first for everything precached, network-first for navigations.
import type { Plugin } from 'vite';
import { existsSync, readdirSync } from 'node:fs';

/** Factory sample files in public/factory (precached so the instrument works offline). */
const factoryFiles = existsSync('public/factory') ? readdirSync('public/factory').map((f) => `./factory/${f}`) : [];

const SW = (version: string, files: string[]) => `// Generated by scripts/sw-plugin.ts
const CACHE = 'tko-${version}';
const FILES = ${JSON.stringify(files)};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  if (req.mode === 'navigate') {
    e.respondWith(fetch(req).catch(() => caches.match('./', { ignoreVary: true })));
    return;
  }
  // ignoreVary: dev/preview servers send 'Vary: Origin', and module script requests carry an Origin header.
  e.respondWith(caches.match(req, { ignoreVary: true }).then((hit) => hit || fetch(req)));
});
`;

export function serviceWorker(): Plugin {
  return {
    name: 'tko-sw',
    apply: 'build',
    generateBundle(_opts, bundle) {
      const files = ['./', ...Object.keys(bundle).filter((f) => !f.endsWith('.map') && !f.endsWith('.woff')).map((f) => `./${f}`)];
      const publicFiles = ['./manifest.webmanifest', './icon.svg', ...factoryFiles];
      const all = [...new Set([...files, ...publicFiles])].filter((f) => !f.includes('lookdev') && !f.includes('render') && !f.includes('bench') && !f.includes('fixture'));
      const version = Date.now().toString(36);
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: SW(version, all) });
    },
  };
}
